export function translate(lang, key, vars) {
  const entry = S[key]
  let s = entry ? entry[lang] ?? entry.hi ?? key : key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
  return s
}

